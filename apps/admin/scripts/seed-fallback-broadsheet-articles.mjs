let successCount = 0;
let failCount = 0;

for (const art of ARTICLES) {
  const publishedAt = new Date(Date.now() - art.published_hours_ago * 3600 * 1000).toISOString();
  
  // Check if article with slug already exists
  const { data: existing } = await supabase
    .from('articles')
    .select('id, status')
    .eq('slug', art.slug)
    .single();

  let articleId = existing?.id;

  try {
    if (!articleId) {
      // Step 1: Insert as DRAFT
      articleId = crypto.randomUUID();
      const { error: insErr } = await supabase
        .from('articles')
        .insert({
          id: articleId,
          title: art.title,
          slug: art.slug,
          excerpt: art.excerpt,
          content: art.content,
          category: art.category,
          district: art.district,
          author_id: authorId,
          author_display_name: art.author_display_name,
          featured_image_url: art.featured_image_url,
          status: 'draft',
          created_at: publishedAt,
          updated_at: publishedAt,
        });

      if (insErr) {
        console.error(`✗ Draft insert error on "${art.slug}":`, insErr.message);
        failCount++;
        continue;
      }
    }

    // Step 2: Transition draft -> review
    const { error: revErr } = await supabase
      .from('articles')
      .update({ status: 'review' })
      .eq('id', articleId);

    if (revErr && !revErr.message.includes('same')) {
      // If already in review or published, continue
    }

    // Step 3: Transition review -> published
    const { error: pubErr } = await supabase
      .from('articles')
      .update({
        status: 'published',
        published_at: publishedAt,
        published_by: authorId,
        updated_at: new Date().toISOString(),
      })
      .eq('id', articleId);

    if (pubErr) {
      console.error(`✗ Publish error on "${art.slug}":`, pubErr.message);
      failCount++;
      continue;
    }

    console.log(`✓ Stored & Published in DB: "${art.title}" (${art.category} • ${art.district})`);
    successCount++;
  } catch (err) {
    console.error(`✗ Exception on "${art.slug}":`, err.message);
    failCount++;
  }
}

console.log(`\n========================================`);
console.log(`Done! Successfully Stored in DB: ${successCount} | Failed: ${failCount}`);

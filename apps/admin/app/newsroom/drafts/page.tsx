'use client';

import { useState, useEffect } from 'react';
import Link from 'next/link';
import { useRouter } from 'next/navigation';
import { supabase } from '@/lib/supabase';

interface FactCheckItem {
  id: string;
  event_id: string;
  article_id: string;
  claim: string;
  verification_status: 'unverified' | 'verified' | 'flagged_disputed';
  source_reference_url: string | null;
  notes: string | null;
  created_at: string;
  article?: {
    id: string;
    title: string;
    slug: string;
    status: string;
    district: string | null;
    category: string;
  };
}

export default function DraftsFactCheckPage() {
  const router = useRouter();
  const [factChecks, setFactChecks] = useState<FactCheckItem[]>([]);
  const [loading, setLoading] = useState(true);
  const [updatingId, setUpdatingId] = useState<string | null>(null);

  useEffect(() => {
    loadFactChecks();
  }, []);

  async function loadFactChecks() {
    try {
      setLoading(true);
      const { data: sessionData } = await supabase.auth.getSession();
      if (!sessionData.session) {
        router.push('/login');
        return;
      }

      // Fetch fact-check claims
      const { data, error } = await supabase
        .from('newsroom_fact_checks')
        .select(`
          *,
          article:articles(id, title, slug, status, district, category)
        `)
        .order('created_at', { ascending: false });

      if (!error && data) {
        setFactChecks(data as unknown as FactCheckItem[]);
      }
    } catch (err) {
      console.error(err);
    } finally {
      setLoading(false);
    }
  }

  async function handleToggleStatus(
    id: string,
    nextStatus: 'unverified' | 'verified' | 'flagged_disputed'
  ) {
    try {
      setUpdatingId(id);
      const { error } = await supabase
        .from('newsroom_fact_checks')
        .update({ verification_status: nextStatus })
        .eq('id', id);

      if (!error) {
        setFactChecks((prev) =>
          prev.map((fc) => (fc.id === id ? { ...fc, verification_status: nextStatus } : fc))
        );
      }
    } catch (err) {
      console.error(err);
    } finally {
      setUpdatingId(null);
    }
  }

  // Group by article
  const groupedByArticle = factChecks.reduce((acc, item) => {
    const articleId = item.article_id || 'unknown';
    if (!acc[articleId]) {
      acc[articleId] = {
        article: item.article,
        claims: [],
      };
    }
    acc[articleId].claims.push(item);
    return acc;
  }, {} as Record<string, { article: FactCheckItem['article']; claims: FactCheckItem[] }>);

  return (
    <div className="mx-auto max-w-7xl px-4 py-8 sm:px-6 lg:px-8">
      {/* Header */}
      <div className="flex flex-col gap-4 sm:flex-row sm:items-center sm:justify-between border-b border-slate-200 pb-5 dark:border-slate-800">
        <div>
          <div className="flex items-center gap-2">
            <span className="text-2xl">📋</span>
            <h1 className="text-2xl font-black text-slate-900 dark:text-white">
              Draft Queue &amp; Fact-Checking Review
            </h1>
          </div>
          <p className="mt-1 text-sm text-slate-600 dark:text-slate-400">
            Verify key factual claims generated by Gemini before human editors approve final publication.
          </p>
        </div>

        <Link
          href="/newsroom"
          className="inline-flex items-center gap-1.5 rounded-lg border border-slate-300 bg-white px-3.5 py-2 text-xs font-bold text-slate-700 hover:bg-slate-50 transition shadow-2xs dark:border-slate-700 dark:bg-slate-900 dark:text-slate-300 dark:hover:bg-slate-800"
        >
          <span>📡</span>
          <span>Back to Monitor</span>
        </Link>
      </div>

      {/* Content */}
      <div className="mt-6 space-y-6">
        {loading ? (
          <div className="rounded-2xl border border-slate-200 bg-white p-12 text-center text-sm font-semibold text-slate-500 dark:border-slate-800 dark:bg-slate-900">
            Loading draft verification checklists...
          </div>
        ) : Object.keys(groupedByArticle).length === 0 ? (
          <div className="rounded-2xl border border-dashed border-slate-300 bg-slate-50 p-12 text-center text-slate-600 dark:border-slate-800 dark:bg-slate-900/50 dark:text-slate-400">
            <span className="text-3xl block mb-2">✨</span>
            <p className="font-bold text-sm">No drafted articles waiting for verification.</p>
            <p className="text-xs mt-1">Approve candidate stories in the Event Monitor to generate drafted articles with fact-check checklists.</p>
          </div>
        ) : (
          Object.entries(groupedByArticle).map(([artId, group]) => {
            const article = group.article;
            const allVerified = group.claims.every((c) => c.verification_status === 'verified');

            return (
              <div
                key={artId}
                className="rounded-2xl border border-slate-200 bg-white p-5 shadow-2xs dark:border-slate-800 dark:bg-slate-900"
              >
                {/* Article Header */}
                <div className="flex flex-wrap items-center justify-between gap-3 border-b border-slate-100 pb-3 dark:border-slate-800">
                  <div>
                    <span className="rounded bg-cyan-100 px-2 py-0.5 text-[10px] font-mono font-bold text-cyan-900 dark:bg-cyan-950 dark:text-cyan-200 mr-2 uppercase">
                      Draft CMS Article
                    </span>
                    <span className="text-xs font-bold text-slate-500">
                      District: {article?.district || 'General J&K'}
                    </span>
                    <h3 className="text-base font-extrabold text-slate-900 dark:text-white mt-1">
                      {article?.title || 'Draft Article'}
                    </h3>
                  </div>

                  <div className="flex items-center gap-2">
                    {article?.id && (
                      <Link
                        href={`/articles/${article.id}/edit`}
                        className="inline-flex items-center gap-1.5 rounded-lg bg-cyan-600 px-3.5 py-1.5 text-xs font-bold text-white shadow-2xs hover:bg-cyan-500 transition"
                      >
                        <span>📝</span>
                        <span>Open in Article Editor</span>
                      </Link>
                    )}
                  </div>
                </div>

                {/* Claims Checklist */}
                <div className="mt-4">
                  <div className="flex items-center justify-between mb-2">
                    <span className="text-xs font-black uppercase tracking-wider text-slate-500">
                      Claims to Verify Before Publishing:
                    </span>
                    <span className={`text-xs font-bold ${allVerified ? 'text-emerald-600' : 'text-amber-600'}`}>
                      {allVerified ? '✓ All Claims Verified' : '⚠️ Unverified Claims Pending'}
                    </span>
                  </div>

                  <div className="space-y-2.5">
                    {group.claims.map((claimItem) => {
                      const isVer = claimItem.verification_status === 'verified';
                      const isDisputed = claimItem.verification_status === 'flagged_disputed';

                      return (
                        <div
                          key={claimItem.id}
                          className={`flex flex-col sm:flex-row sm:items-center justify-between gap-3 rounded-xl border p-3 text-xs transition ${
                            isVer
                              ? 'border-emerald-200 bg-emerald-50/60 dark:border-emerald-800/60 dark:bg-emerald-950/20'
                              : isDisputed
                              ? 'border-rose-200 bg-rose-50/60 dark:border-rose-800/60 dark:bg-rose-950/20'
                              : 'border-slate-200 bg-slate-50/60 dark:border-slate-800 dark:bg-slate-800/40'
                          }`}
                        >
                          <div className="flex items-start gap-2.5">
                            <span className="text-sm mt-0.5">
                              {isVer ? '✅' : isDisputed ? '❌' : '🔍'}
                            </span>
                            <div>
                              <p className="font-semibold text-slate-900 dark:text-white leading-relaxed">
                                {claimItem.claim}
                              </p>
                              {claimItem.notes && (
                                <p className="text-[11px] text-amber-700 dark:text-amber-400 mt-0.5">
                                  ⚠️ {claimItem.notes}
                                </p>
                              )}
                            </div>
                          </div>

                          <div className="flex items-center gap-1.5 shrink-0 self-end sm:self-center">
                            <button
                              type="button"
                              onClick={() => handleToggleStatus(claimItem.id, 'verified')}
                              disabled={updatingId === claimItem.id}
                              className={`rounded-md px-2.5 py-1 text-xs font-bold transition ${
                                isVer
                                  ? 'bg-emerald-600 text-white'
                                  : 'bg-white border border-slate-200 text-slate-700 hover:bg-emerald-50 hover:text-emerald-800 dark:bg-slate-800 dark:border-slate-700 dark:text-slate-300'
                              }`}
                            >
                              Verify
                            </button>
                            <button
                              type="button"
                              onClick={() => handleToggleStatus(claimItem.id, 'flagged_disputed')}
                              disabled={updatingId === claimItem.id}
                              className={`rounded-md px-2.5 py-1 text-xs font-bold transition ${
                                isDisputed
                                  ? 'bg-rose-600 text-white'
                                  : 'bg-white border border-slate-200 text-slate-700 hover:bg-rose-50 hover:text-rose-800 dark:bg-slate-800 dark:border-slate-700 dark:text-slate-300'
                              }`}
                            >
                              Dispute
                            </button>
                          </div>
                        </div>
                      );
                    })}
                  </div>
                </div>
              </div>
            );
          })
        )}
      </div>
    </div>
  );
}
